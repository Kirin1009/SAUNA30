import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

// Export existing art code, not the app bootstrap or its persistent state.
const root = new URL('../../../', import.meta.url);
const source = readFileSync(new URL('totonoi/index.html', root), 'utf8');
const context = { window: {} };
vm.runInNewContext(readFileSync(new URL('totonoi/catalog.js', root), 'utf8'), context);
const ids = ['g4', 'g1', 'g2', 'g5', 'a1'];
const facilities = ids.map(id => context.window.CATALOG.FACILITIES.find(f => f.id === id));
if (facilities.some(f => !f)) throw new Error('Missing catalog fixture');
const extract = (start, end) => {
  const a = source.indexOf(start), b = source.indexOf(end, a);
  if (a < 0 || b < 0) throw new Error(`Cannot extract ${start}`);
  return source.slice(a, b).trim();
};
const esc = extract('const esc=', 'const rad=');
const hash = source.match(/const sealHash=.*?; \};/)[0];
const badges = extract('function sealBadges(', 'function facSeal(');
const seal = extract('function facSeal(', '\n/*');
const filter = source.match(/<filter id="sealtex"[\s\S]*?<\/filter>/)[0];
const output = `// Generated by prepare.mjs from main 7573a5d; facSeal and sealBadges unchanged.\n`
  + `const FACS=${JSON.stringify(facilities)};\n${esc}\n${hash}\n`
  + `const obsTemps=()=>[]; // No personal observations in these catalog-only seals.\n`
  + `${badges}\n${seal}\nconst SEAL_FILTER=${JSON.stringify(filter)};\n`;
writeFileSync(new URL('existing-seals.js', import.meta.url), output);
console.log('Exported existing seals and five catalog entries to', fileURLToPath(new URL('existing-seals.js', import.meta.url)));
